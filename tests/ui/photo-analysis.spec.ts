import {test,expect,type Page} from '@playwright/test'
async function setup(page:Page,mobile:boolean){
 await page.goto('/');await page.locator(mobile?'.mobile-nav':'.sidebar').getByRole('button',{name:'Journal',exact:false}).click()
 const data=await page.evaluate(()=>{const c=document.createElement('canvas');c.width=400;c.height=300;return c.toDataURL('image/png').split(',')[1]!})
 await page.getByLabel('Choisir une photo dans la galerie ou les fichiers').setInputFiles({name:'repas.png',mimeType:'image/png',buffer:Buffer.from(data,'base64')})
 await expect(page.getByRole('button',{name:'Analyser la photo',exact:true})).toBeVisible()
}
test('photo proposal → correction → source → draft → explicit confirmation',async({page,isMobile})=>{
 await setup(page,isMobile)
 const section=page.getByRole('region',{name:'Analyse photographique'})
 await section.getByRole('button',{name:'Analyser la photo',exact:true}).click()
 await expect(section.getByLabel('Aliment estimé')).toHaveCount(2)
 await expect(section.getByLabel('Quantité estimée').nth(1)).toHaveValue('')
 await expect(section.getByRole('button',{name:'Créer un brouillon avec ces aliments'})).toBeDisabled()
 await section.getByRole('button',{name:'Retirer la proposition 2'}).click()
 await section.getByLabel('Quantité estimée').fill('234')
 await section.getByRole('button',{name:'Choisir / remplacer la fiche 1'}).click()
 await section.getByRole('button',{name:'Rechercher',exact:true}).click()
 await section.getByRole('button',{name:/Pois chiches.*Fixture/}).first().click()
 await section.getByRole('button',{name:'Retenir cette fiche'}).click()
 await section.getByRole('button',{name:'Créer un brouillon avec ces aliments'}).click()
 const draft=page.locator('.journal-meal').filter({has:page.locator('input[value="Depuis une photo"]')})
 await expect(draft).toHaveCount(1);await expect(draft.locator('input[value="234"]')).toHaveCount(1)
 await expect(draft).toContainText('Pois chiches')
 const before=await page.locator('.journal-confirmed').count()
 await draft.getByRole('button',{name:'Confirmer ce repas'}).click()
 await expect(page.locator('.journal-confirmed')).toHaveCount(before+1)
})
test('proposal refusal never creates a draft; remote photo deletion independent',async({page,isMobile})=>{
 await setup(page,isMobile);const count=await page.locator('.journal-confirmed').count()
 await page.getByRole('button',{name:'Analyser la photo',exact:true}).click()
 await page.getByRole('button',{name:'Retirer la proposition 2'}).click();await page.getByRole('button',{name:'Retirer la proposition 1'}).click()
 await expect(page.getByRole('button',{name:'Créer un brouillon avec ces aliments'})).toBeDisabled()
 await page.getByRole('button',{name:'Supprimer la photo distante'}).click()
 await expect(page.locator('.journal-confirmed')).toHaveCount(count)
})
test('offline analysis remains pending after reload until manual retry',async({page,isMobile,context})=>{
 await setup(page,isMobile);await context.setOffline(true)
 await page.getByRole('button',{name:'Analyser la photo',exact:true}).click()
 await expect(page.getByRole('button',{name:'Relancer l’analyse en attente'})).toBeVisible()
 await context.setOffline(false);await page.reload()
 await page.locator(isMobile?'.mobile-nav':'.sidebar').getByRole('button',{name:'Journal',exact:false}).click()
 await expect(page.getByRole('button',{name:'Relancer l’analyse en attente'})).toBeVisible()
 await page.getByRole('button',{name:'Annuler la demande'}).click()
 await expect(page.getByRole('button',{name:'Analyser la photo',exact:true})).toBeVisible()
})
