import { expect, test } from '@playwright/test'

test('optional profile guide can be skipped or replayed and persists changes', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Configurer mon profil' }).click()
  await expect(page.getByText(/Étape 1 sur 3/)).toBeVisible()
  await page.getByRole('button', { name: 'Passer la configuration' }).click()
  await page.reload()
  await expect(page.getByRole('button', { name: 'Configurer mon profil' })).toHaveCount(0)
  await page.getByRole('button', { name: 'Ouvrir le menu utilisateur' }).filter({ visible: true }).first().click()
  await page.getByRole('menuitem', { name: 'Mon profil et préférences' }).click()
  await page.getByRole('button', { name: 'Relancer la configuration' }).click()
  await page.getByLabel('Poids cible (kg)').fill('68.5')
  await page.getByRole('button', { name: 'Continuer' }).click()
  await page.getByLabel('Nombre de repas par jour').fill('4')
  await page.getByRole('button', { name: 'Retour' }).click()
  await expect(page.getByLabel('Poids cible (kg)')).toHaveValue('68.5')
  await page.getByRole('button', { name: 'Continuer' }).click()
  await page.getByRole('button', { name: 'Continuer' }).click()
  await page.getByRole('button', { name: 'Enregistrer mon profil' }).click()
  await expect(page.getByLabel('Poids cible (kg)')).toHaveValue('68.5')
  await expect(page.getByLabel('Nombre de repas par jour')).toHaveValue('4')
})

test('waist measurements are dated, validated and separate from weight', async ({ page }) => {
  await page.goto('/')
  const track = () => page.getByRole('button', { name: /Suivi/ }).filter({ visible: true }).first().click()
  await track()
  const waist = page.getByRole('region', { name: 'Tour de taille' })
  const cm = waist.getByLabel('Tour de taille (cm)')
  await cm.fill('15')
  expect(await cm.evaluate((input: HTMLInputElement) => input.validity.rangeUnderflow)).toBe(true)
  await waist.getByLabel('Date du tour de taille').fill('2026-11-05')
  await cm.fill('81.2')
  await waist.getByRole('button', { name: 'Enregistrer le tour de taille' }).click()
  await expect(waist.locator('.measurement-list').getByText('81,2 cm')).toBeVisible()
  await page.reload()
  await track()
  await expect(waist.locator('.measurement-list').getByText('81,2 cm')).toBeVisible()
  await expect(page.getByRole('group', { name: 'Évolution du poids en kilogrammes' }).getByRole('button')).toHaveCount(3)
  page.once('dialog', dialog => dialog.accept())
  await waist.getByRole('button', { name: 'Supprimer le tour de taille du 2026-11-05' }).click()
  await expect(waist.getByText('Aucune mesure de tour de taille.')).toBeVisible()
})
