test('keyboard: account menu opens, navigates and returns focus on Escape', async ({ page }) => {
  const trigger = page.getByRole('button', { name: 'Ouvrir le menu utilisateur', exact: true }).last()
  await trigger.focus()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('menuitem', { name: 'Mon profil et préférences' })).toBeFocused()
  await page.keyboard.press('ArrowDown')
  await expect(page.getByRole('menuitem', { name: 'Se déconnecter' })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('menu')).toHaveCount(0)
  await expect(trigger).toBeFocused()
})
