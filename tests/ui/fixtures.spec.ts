import { expect, test, type Page } from '@playwright/test'

const observations = new WeakMap<Page, { errors: string[]; apiRequests: string[] }>()
async function navigate(page: Page, mobile: boolean, label: string) {
  await page.locator(mobile ? '.mobile-nav' : '.sidebar').getByRole('button', { name: label, exact: false }).click()
}
const historySection = (page: Page, heading: string) => page.locator('section.data-card').filter({ has: page.getByRole('heading', { name: heading, exact: true }) })
const today = () => new Date().toISOString().slice(0, 10)

test.beforeEach(async ({ page }) => {
  const observed = { errors: [] as string[], apiRequests: [] as string[] }
  observations.set(page, observed)
  page.on('pageerror', error => observed.errors.push(error.message))
  page.on('request', request => { if (new URL(request.url()).pathname.startsWith('/api/')) observed.apiRequests.push(request.url()) })
  await page.goto('/')
  await expect(page.getByText(/MODE RECETTE UI/)).toBeVisible()
})
test.afterEach(async ({ page }) => {
  expect(observations.get(page)?.errors).toEqual([])
  expect(observations.get(page)?.apiRequests, 'fixtures must never fall through to a Worker or remote service').toEqual([])
})

test('history: 20 recent meals, older dates, search and date filters reset pagination', async ({ page, isMobile }, info) => {
  await navigate(page, isMobile, 'Historique')
  const recent = historySection(page, '20 consommations les plus récentes')
  const filtered = historySection(page, 'Historique filtré')
  await expect(recent.locator('article')).toHaveCount(20)
  await filtered.getByRole('button', { name: 'Suivant', exact: true }).click()
  await expect(filtered.locator('article')).toHaveCount(4)
  await page.getByLabel('Depuis', { exact: true }).fill(today())
  await expect(filtered.locator('article')).toHaveCount(1)
  await expect(filtered.locator('.history-pages')).toContainText('1–1 / 1')
  await expect(recent.locator('article')).toHaveCount(20)
  await page.getByLabel('Depuis', { exact: true }).fill('')
  await filtered.getByRole('button', { name: 'Suivant', exact: true }).click()
  await page.getByLabel('Jusqu’au', { exact: true }).fill(today())
  await expect(filtered.locator('.history-pages')).toContainText('1–20 / 24')
  await page.getByLabel('Rechercher un repas ou un aliment').fill('dejeuner')
  await expect(filtered.locator('article')).toHaveCount(1)
  await page.getByLabel('Rechercher un repas ou un aliment').fill('introuvable')
  await expect(filtered.getByText('Aucun résultat pour ces filtres.')).toBeVisible()
  await expect(page.locator('body')).not.toContainText('Serveur inaccessible')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: info.outputPath('history.png'), fullPage: true })
})

test('journal: correction 234 g counts once, keeps recipe and cancels without duplication', async ({ page, isMobile }, info) => {
  await navigate(page, isMobile, 'Journal')
  await expect(page.locator('.journal-confirmed')).toHaveCount(1)
  await page.getByRole('button', { name: 'Corriger', exact: true }).click()
  await page.getByLabel('Quantité consommée').fill('234')
  await page.getByLabel('Quantité consommée').blur()
  await expect(page.locator('.journal-food')).toContainText(['Pois chiches (synthétique)', 'Bol céréales & pois chiches (synthétique)'])
  await page.getByRole('button', { name: 'Confirmer ce repas', exact: true }).click()
  await expect(page.locator('.journal-section-heading h2')).toHaveText('0 brouillon(s) · 1 confirmé(s)')
  await expect(page.locator('.journal-confirmed')).toHaveCount(1)
  await expect(page.locator('.journal-confirmed-items')).toContainText('234 g')
  await expect(page.locator('.journal-total strong')).toHaveText(['395 kcal', '25.3 g', '22.7 g', '7.4 g', '21.6 g'])
  await page.screenshot({ path: info.outputPath('corrected-234g.png'), fullPage: true })
  await navigate(page, isMobile, 'Historique')
  await expect(historySection(page, '20 consommations les plus récentes').locator('article')).toHaveCount(20)
  await expect(historySection(page, 'Historique filtré').locator('.history-pages')).toContainText('/ 24')
  await navigate(page, isMobile, 'Journal')
  await page.locator('.journal-confirmed').getByRole('button', { name: 'Supprimer', exact: true }).click()
  await expect(page.locator('.journal-section-heading h2')).toHaveText('0 brouillon(s) · 0 confirmé(s)')
  await expect(page.locator('.journal-confirmed')).toHaveCount(0)
  await expect(page.locator('.journal-sync')).not.toContainText(/Serveur inaccessible|Erreur/)
})

