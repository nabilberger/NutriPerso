test('models: explicit creation, rename, independent reuse and deletion', async ({ page, isMobile }) => {
  await navigate(page, isMobile, 'Historique')
  const recent = historySection(page, '20 consommations les plus récentes')
  await recent.locator('article').first().getByRole('button', { name: 'Enregistrer comme modèle' }).click()
  await page.getByLabel('Nom du modèle', { exact: true }).fill('Modèle recette test')
  await page.getByRole('dialog').getByRole('button', { name: 'Enregistrer', exact: true }).click()
  const models = historySection(page, 'Modèles enregistrés')
  let saved = models.locator('article').filter({ hasText: 'Modèle recette test' })
  await expect(saved).toHaveCount(1)
  page.once('dialog', dialog => dialog.accept('Modèle renommé test'))
  await saved.getByRole('button', { name: 'Renommer', exact: true }).click()
  saved = models.locator('article').filter({ hasText: 'Modèle renommé test' })
  await expect(saved).toHaveCount(1)
  await saved.getByRole('button', { name: 'Réutiliser', exact: true }).click()
  await expect(page.locator('.journal-section-heading h2')).toHaveText('1 brouillon(s) · 1 confirmé(s)')
  await expect(page.getByLabel('Quantité consommée')).toHaveValue('100')
  await page.getByLabel('Quantité consommée').fill('150')
  await navigate(page, isMobile, 'Historique')
  await expect(recent.locator('article').first()).toContainText('Déjeuner démo')
  saved = models.locator('article').filter({ hasText: 'Modèle renommé test' })
  page.once('dialog', dialog => dialog.dismiss())
  await saved.getByRole('button', { name: 'Supprimer', exact: true }).click()
  await expect(saved).toHaveCount(1)
  page.once('dialog', dialog => dialog.accept())
  await saved.getByRole('button', { name: 'Supprimer', exact: true }).click()
  await expect(saved).toHaveCount(0)
  await navigate(page, isMobile, 'Journal')
  await expect(page.getByLabel('Quantité consommée')).toHaveValue('150')
  await expect(page.locator('.journal-confirmed-items')).toContainText('100 g')
})

