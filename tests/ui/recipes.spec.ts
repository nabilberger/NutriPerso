import { expect, test, type Page } from '@playwright/test'
const nav = (page: Page, mobile: boolean, name: string) => page.locator(mobile ? '.mobile-nav' : '.sidebar').getByRole('button', { name, exact: false }).click()
const row = (page: Page, name: string) => page.locator('.recipes-list article').filter({ has: page.getByRole('heading', { name, exact: true }) })
async function addUsda(page: Page, query = 'pois', amount = '200') {
  await page.getByRole('button', { name: 'Ajouter un ingrédient', exact: true }).click()
  await page.getByLabel('Rechercher dans FoodData Central').fill(query)
  await page.locator('.recipe-picker').getByRole('button', { name: 'Rechercher', exact: true }).click()
  await page.locator('.journal-search-results button').first().click()
  await page.locator('.journal-food-detail').getByLabel('Quantité', { exact: true }).fill(amount)
  await page.locator('.journal-food-detail').getByRole('button', { name: 'Ajouter cet ingrédient', exact: true }).click()
}
async function create(page: Page, name = 'Préparation maison test') {
  await page.getByRole('button', { name: 'Créer une recette', exact: true }).click()
  await page.getByLabel('Nom de la recette', { exact: true }).fill(name)
  await page.getByLabel('Nombre de portions').fill('2')
  await addUsda(page)
}
async function confirm(page: Page) {
  await page.getByRole('button', { name: 'Confirmer la recette', exact: true }).click()
  await expect(page.getByText('Recette confirmée. Elle peut être utilisée dans le journal.', { exact: true })).toBeVisible()
}
async function records(page: Page) {
  return page.evaluate(() => {
    const key=Object.keys(localStorage).find(k=>k.startsWith('nutrip-journal-v1:'))
    return key ? JSON.parse(localStorage.getItem(key)!).snapshots : []
  })
}
const observations = new WeakMap<Page, string[]>()
test.afterEach(async ({ page }) => { expect(observations.get(page)).toEqual([]) })
test.beforeEach(async ({ page }) => {
  const observed: string[] = []; observations.set(page, observed)
  page.on('pageerror', error => observed.push(error.message))
  page.on('request', request => { if (new URL(request.url()).pathname.startsWith('/api/')) observed.push('Unexpected live API: ' + request.url()) })
  await page.goto('/')
  await expect(page.getByText(/MODE RECETTE UI/)).toBeVisible()
})

